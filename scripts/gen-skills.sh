#!/usr/bin/env bash
#
# gen-skills.sh - write the kit's skills (skills/<name>/SKILL.md) from the doctrine. Never by hand.
#
# The problem it solves: a skill is the first text an agent reads, and the kit's rules live in AGENTS.md and
# doctrine/NEXT.md. A skill written by hand is a second copy of them, and copies drift: a fork that copied an 8,400-
# character "constitution" into nine skills lost about ten rules on the way and was already stale a week later; and a
# skill that carried the whole constitution was read around, not invoked. So each SKILL.md here is thin, and every
# sentence in it that states a rule is EXTRACTED from the doctrine when this script runs:
#   - the six rules every skill carries: the block between `<!-- invariants:begin -->` and `<!-- invariants:end -->`
#     in AGENTS.md, byte for byte, markers included;
#   - "This phase": the NEXT.md rows the skill owns, each with its "do this" cell, read from the table by id;
#   - "Gate": the phase's cell of AGENTS.md section 3;
#   - "Read on entry": the path, and AGENTS.md section 7's own line for it when it has one;
#   - the entry skill's four steps: sentences of AGENTS.md, each checked to be there before it is written;
#   - the doctor's checks: each script's own first line (line 3 of its header).
# What is NOT extracted is short and kept as DATA below: which skill owns which rows, the trigger words of each
# description, and the "Read on entry" / "Read when" lists. The only prose this script adds is structure: headings,
# the labels of the entry skill's steps, the "Everything else is in AGENTS.md" line and the "Done when" line.
# Paths: every file a skill names is written `{{KIT}}/<path>`, <path> from the kit's root; a path inside a cell or a
# sentence taken from the doctrine (`scripts/battery.sh`, `JUDGES.md`) gets the same prefix when it names a file of the
# kit (at the root, or a bare name under doctrine/), and is left alone otherwise (`pending/<id>.t.sol`, `STATE.md`).
# `{{KIT}}` is replaced by scripts/install-skills.sh with where the kit is, seen from the project (default
# lib/hook-gauntlet). scripts/skills-check.sh regenerates into a temporary directory and compares: drift is red.
#
# The design (thin skills, the row -> skill table, the per-phase shape This phase / Gate / Read on entry / Read when /
# Done when, the entry skill's four steps) is Pedro Santana's, from his fork of this kit that turned it into skills
# (0xZ0uk/hook-gauntlet, 2026-09); what changed is that nothing in a skill is written by hand.
#
# Usage:   scripts/gen-skills.sh [--out DIR]
#   --out DIR   where to write <name>/SKILL.md (default: the kit's skills/). A <name>/SKILL.md that is there and was not
#               written by this script (no "generated by" line) is refused, never overwritten.
# Output:  "wrote <name>/SKILL.md (<bytes> bytes, <lines> lines)" per skill, then "gen-skills: <n> skills written to <DIR>".
# Exit:    0 written; 2 REFUSED - AGENTS.md's invariants markers are not one begin then one end, a row of NEXT.md's
#          table no skill owns (or a row owned that the table does not have), a phase with no gate cell, a sentence
#          quoted here that AGENTS.md no longer has, a description YAML would misread, bad arguments: one line on stderr.

set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
KIT="$(cd "$HERE/.." && pwd)"
OUT="$KIT/skills"

refuse() { echo "gen-skills: REFUSED - $*" >&2; exit 2; }

while [ $# -gt 0 ]; do
  case "$1" in
    --out) [ $# -ge 2 ] || refuse "--out has no value."; OUT="$2"; shift 2 ;;
    *) refuse "unknown argument '$1'." ;;
  esac
done

AGENTS="$KIT/AGENTS.md"; NEXTMD="$KIT/doctrine/NEXT.md"
[ -f "$AGENTS" ] || refuse "no AGENTS.md at $AGENTS."
[ -f "$NEXTMD" ] || refuse "no doctrine/NEXT.md at $NEXTMD."
GENLINE='<!-- generated by scripts/gen-skills.sh from AGENTS.md and doctrine/NEXT.md: do not edit -->'

