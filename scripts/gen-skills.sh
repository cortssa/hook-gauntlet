# ------------------------------------------------------------------------------------------------ helpers
trim() { local s="$1"; s="${s#"${s%%[![:space:]]*}"}"; printf '%s' "${s%"${s##*[![:space:]]}"}"; }
squash() { printf '%s' "$1" | tr '\n\t' '  ' | tr -s ' '; }   # whitespace normalised, for "is this sentence there?"

# kitpaths <text>: inside every `...`, each word that names a file or directory of the kit gets the {{KIT}}/ prefix - a
# word with a "/" or a file extension, found at the kit's root (`scripts/battery.sh`, `QUICKSTART.md`, `state/`), or a
# bare *.md found under doctrine/ (NEXT.md writes `JUDGES.md` for doctrine/JUDGES.md). Anything else is left as it is:
# `STATE.md`, `pending/<id>.t.sol` and `.gauntlet/` are the project's, not the kit's.
BT='`'
KP_RE="^([^${BT}]*)${BT}([^${BT}]*)${BT}(.*)\$"
kitword() {
  local w="$1"
  if [[ $w =~ ^[A-Za-z0-9_][A-Za-z0-9._/-]*$ ]] && [[ $w == */* || $w =~ \.[a-z]+$ ]] && [ -e "$KIT/$w" ]; then
    printf '{{KIT}}/%s' "$w"
  elif [[ $w =~ ^[A-Za-z0-9_][A-Za-z0-9._-]*\.md$ ]] && [ -f "$KIT/doctrine/$w" ]; then
    printf '{{KIT}}/doctrine/%s' "$w"
  else
    printf '%s' "$w"
  fi
}
kitpaths() {
  local s="$1" out="" tok w sep
  while [[ $s =~ $KP_RE ]]; do
    out+="${BASH_REMATCH[1]}$BT"; tok="${BASH_REMATCH[2]}"; s="${BASH_REMATCH[3]}"
    sep=""
    while [[ $tok =~ ^([^ ]*)( +)(.*)$ ]]; do
      w="${BASH_REMATCH[1]}"; sep="${BASH_REMATCH[2]}"; tok="${BASH_REMATCH[3]}"
      out+="$(kitword "$w")$sep"
    done
    out+="$(kitword "$tok")$BT"
  done
  printf '%s' "$out$s"
}

# ------------------------------------------------------------------------------------------------ what the doctrine says
# the six rules: AGENTS.md between its markers, markers included, byte for byte
read -r nb ne lb le <<< "$(LC_ALL=C awk '
  /^<!-- invariants:begin -->[ \t\r]*$/ { nb++; if (nb == 1) lb = NR }
  /^<!-- invariants:end -->[ \t\r]*$/   { ne++; if (ne == 1) le = NR }
  END { printf "%d %d %d %d\n", nb + 0, ne + 0, lb + 0, le + 0 }' "$AGENTS")"
{ [ "$nb" = 1 ] && [ "$ne" = 1 ] && [ $((le - lb)) -ge 2 ]; } \
  || refuse "AGENTS.md has $nb '<!-- invariants:begin -->' and $ne '<!-- invariants:end -->' line(s): exactly one of each, begin first, the rules between them."
INVARIANTS="$(sed -n "${lb},${le}p" "$AGENTS")"

# NEXT.md's table: "id US action" per row, as next.sh reads it (every line of the table is a row of four cells)
declare -a TIDS=()
declare -A ACTION=()
while IFS=$'\037' read -r t_id t_act; do
  [ "$t_id" = BAD ] && refuse "doctrine/NEXT.md, line $t_act of the table is not a row of four cells."
  TIDS+=("$t_id"); ACTION[$t_id]="$t_act"
done < <(LC_ALL=C awk '
  { sub(/\r$/, "") }
  /^## / { intable = ($0 ~ /^## The table/); started = 0; ended = 0; next }
  !intable { next }
  !started && /^\|/ { started = 1 }
  !started { next }
  !ended && /^[ \t]*$/ { ended = 1; next }
  ended && !/^\|/ { next }
  {
    line = $0; n = gsub(/[|]/, "|", line)
    if ($0 ~ /^\|[-:| ]+$/ && n == 5) next
    split($0, c, /[|]/); id = c[2]; gsub(/^[ \t]+|[ \t]+$/, "", id)
    if ($0 !~ /^\|/ || n != 5 || id == "" || id ~ /[ \t]/) { print "BAD\037" NR; next }
    if (id == "#") next
    act = c[4]; gsub(/^[ \t]+|[ \t]+$/, "", act)
    print id "\037" act
  }' "$NEXTMD")
[ "${#TIDS[@]}" -gt 0 ] || refuse "doctrine/NEXT.md has no table under '## The table'."

# AGENTS.md section 3: phase -> name and gate cell; section 7: path -> its line
declare -A PNAME=() PGATE=() WHERE=()
while IFS=$'\037' read -r g_id g_name g_gate; do
  [ "$g_id" = BAD ] && refuse "AGENTS.md section 3, line $g_name: a phase row that is not four cells."
  PNAME[$g_id]="$g_name"; PGATE[$g_id]="$g_gate"
done < <(LC_ALL=C awk '
  { sub(/\r$/, "") }
  /^## / { in3 = ($0 ~ /^## 3\. /); next }
  in3 && /^\| [0-9] \|/ {
    line = $0; n = gsub(/[|]/, "|", line)
    if (n != 5) { print "BAD\037" NR; next }
    split($0, c, /[|]/)
    for (i = 2; i <= 5; i++) gsub(/^[ \t]+|[ \t]+$/, "", c[i])
    name = c[3]; gsub(/\*/, "", name)
    print c[2] "\037" name "\037" c[5]
  }' "$AGENTS")
while IFS=$'\037' read -r w_path w_line; do WHERE[$w_path]="$w_line"; done < <(LC_ALL=C awk '
  { sub(/\r$/, "") }
  /^## / { in7 = ($0 ~ /^## 7\. /); next }
  in7 && /^[a-z][A-Za-z0-9._\/-]* +[^ ]/ { p = $1; d = $0; sub(/^[^ ]+ +/, "", d); print p "\037" d }' "$AGENTS")

# ------------------------------------------------------------------------------------------------ the data, checked
declare -a NAMES=()
declare -A PHASES=() OWNS=() WHAT=() TRIG=() OWNER=() PART=()
while IFS='|' read -r s_name s_ph s_rows s_cut s_what; do
  s_name="$(trim "$s_name")"; [ -n "$s_name" ] || continue
  NAMES+=("$s_name"); PHASES[$s_name]="$(trim "$s_ph")"; OWNS[$s_name]="$(trim "$s_rows")"; WHAT[$s_name]="$(trim "$s_what")"
  PART[$s_name]="$(trim "$s_cut")"
done <<< "$SKILLS"
while IFS='|' read -r t_name t_text; do
  t_name="$(trim "$t_name")"; [ -n "$t_name" ] || continue; TRIG[$t_name]="$(trim "$t_text")"
done <<< "$TRIGGERS"
for s in "${NAMES[@]}"; do
  [ -n "${TRIG[$s]:-}" ] || refuse "skill $s has no trigger words (TRIGGERS)."
  for p in ${PHASES[$s]//-/}; do [ -n "${PGATE[$p]:-}" ] || refuse "skill $s quotes the gate of phase $p, which AGENTS.md section 3 does not have."; done
  for r in ${OWNS[$s]//-/}; do
    id="${r%@*}"
    [ -n "${ACTION[$id]+x}" ] || refuse "skill $s owns row $id, which doctrine/NEXT.md's table does not have."
    OWNER[$id]="${OWNER[$id]:-}${OWNER[$id]:+ }$s"
  done
done
for id in "${TIDS[@]}"; do
  [ -n "${OWNER[$id]:-}" ] || refuse "row $id of doctrine/NEXT.md's table is owned by no skill: give it one in gen-skills.sh (SKILLS)."
done
while IFS='|' read -r r k path note; do
  r="$(trim "$r")"; [ -n "$r" ] || continue
  [ -n "${PHASES[$r]+x}" ] || refuse "READS names a skill '$r' that SKILLS does not have."
  case "$(trim "$k")" in entry | when) ;; *) refuse "READS: '$(trim "$k")' for $r is neither entry nor when." ;; esac
  [ -n "$(trim "$path")" ] && [ -n "$(trim "$note")" ] || refuse "READS: a line for $r has no path or no note."
done <<< "$READS"
for t in "${!TRIG[@]}"; do [ -n "${PHASES[$t]+x}" ] || refuse "TRIGGERS names a skill '$t' that SKILLS does not have."; done
while IFS='|' read -r q_label q_text; do
  q_label="$(trim "$q_label")"; [ -n "$q_label" ] || continue; q_text="$(trim "$q_text")"
  case "$(squash "$(cat "$AGENTS")")" in
    *"$(squash "$q_text")"*) ;;
    *) refuse "the entry skill's step '$q_label' quotes a sentence AGENTS.md no longer has: '${q_text:0:80}...'." ;;
  esac
done <<< "$STEPS"

# partcell <cell> <bytes>: the cell up to its last sentence that ends within <bytes> (a ".", "?" or "!", a closing "**"
# or ")" after it, then a space); nothing when no sentence ends that early
partcell() {
  printf '%s\n' "$1" | LC_ALL=C awk -v max="$2" '{
    s = $0; n = 0; best = 0
    while (match(s, /[.?!](\*\*)?\)? /)) { n += RSTART + RLENGTH - 1; if (n - 1 <= max) best = n - 1; s = substr(s, RSTART + RLENGTH) }
    if (best > 0) print substr($0, 1, best) }'
}
for s in "${NAMES[@]}"; do
  for pc in ${PART[$s]//-/}; do
    id="${pc%%:*}"; lim="$CUT"; [ "$pc" = "$id" ] || lim="${pc#*:}"
    [[ $lim =~ ^[1-9][0-9]*$ ]] || refuse "skill $s quotes row $id in part within '$lim' bytes, which is not a number."
    case " ${OWNS[$s]} " in *" $id "*) ;; *) refuse "skill $s quotes row $id in part, and does not own it." ;; esac
    [ -n "$(partcell "${ACTION[$id]}" "$lim")" ] || refuse "row $id's cell has no sentence that ends within $lim bytes: skill $s cannot quote it in part."
  done
done

# rowlist <skill>: "4b, 5, 6" (a row@phase as "4 (phase 0)"), in the table's order
rowlist() {
  local s="$1" id r out=""
  for id in "${TIDS[@]}"; do
    for r in ${OWNS[$s]//-/}; do
      [ "${r%@*}" = "$id" ] || continue
      if [ "$r" != "$id" ]; then out+="${out:+, }$id (phase ${r#*@})"; else out+="${out:+, }$id"; fi
    done
  done
  printf '%s' "$out"
}
# phasewords <skill>: "phase 2 (Foundry sketch) and phase 3 (Battery)"
phasewords() {
  local p out="" n=0
  for p in ${PHASES[$1]}; do n=$((n + 1)); [ $n -gt 1 ] && out+=" and "; out+="phase $p (${PNAME[$p]})"; done
  printf '%s' "$out"
}

describe() {
  local s="$1" what rows d
  what="${WHAT[$s]}"
  [ "$what" = "-" ] && what="$(phasewords "$s" | sed 's/^p/P/') of hook-gauntlet, the route that takes a Uniswap v4 hook to audit-ready"
  rows="$(rowlist "$s")"
  case "$rows" in "") ;; *,*) what+="; doctrine/NEXT.md rows $rows" ;; *) what+="; doctrine/NEXT.md row $rows" ;; esac
  d="$what. Use for ${TRIG[$s]}."
  case "$d" in *': '* | *' #'* | *'"'* | *'`'*) refuse "the description of $s has ': ', ' #', a quote or a backtick, which YAML or the harness would misread." ;; esac
  [ "${#d}" -le 1024 ] || refuse "the description of $s is ${#d} characters, over the 1024 a harness reads."
  printf '%s' "$d"
}

# ------------------------------------------------------------------------------------------------ one SKILL.md
render() {
  local s="$1" p r id n label text line path kind note script pc lim
  printf -- '---\nname: %s\ndescription: %s\n---\n%s\n\n' "$s" "${DESC[$s]}" "$GENLINE"

  echo "## Rules that hold in every phase"
  echo
  printf '%s\n' "$INVARIANTS"
  echo
  echo 'Everything else is in `{{KIT}}/AGENTS.md`; where any file and it disagree, it wins.'
  echo

  if [ "$s" = hook-gauntlet ]; then
    echo "## This skill"
    echo
    n=0
    while IFS='|' read -r label text; do
      label="$(trim "$label")"; [ -n "$label" ] || continue; text="$(trim "$text")"; n=$((n + 1))
      case "$text" in *[.?!]) ;; *) text+="." ;; esac
      printf '%d. **%s.** %s\n' "$n" "$label" "$(kitpaths "$text")"
    done <<< "$STEPS"
    echo
  fi
  if [ "$s" = hook-gauntlet-doctor ]; then
    echo "## This skill"
    echo
    echo "No row of \`{{KIT}}/doctrine/NEXT.md\` is its own. The checks, each script's own first line:"
    echo
    for script in $DOCTOR_SCRIPTS; do
      line="$(sed -n 3p "$KIT/scripts/$script" | sed 's/^# *//')"
      [ -n "$line" ] || refuse "scripts/$script has no header line 3 for the doctor to quote."
      printf -- '- `{{KIT}}/scripts/%s` - %s\n' "$script" "${line#"$script" - }"
    done
    echo
  fi

  if [ "${OWNS[$s]}" != "-" ]; then
    if [ "$s" = hook-gauntlet ]; then echo "## The rows that stay with this skill"; else echo "## This phase"; fi
    echo
    echo "From \`{{KIT}}/doctrine/NEXT.md\`, the rows this skill owns and what each says to do:"
    echo
    for id in "${TIDS[@]}"; do
      for r in ${OWNS[$s]}; do
        [ "${r%@*}" = "$id" ] || continue
        if [ "$r" != "$id" ]; then label="Row $id, phase ${r#*@}"; else label="Row $id"; fi
        text="${ACTION[$id]}"
        for pc in ${PART[$s]//-/}; do
          [ "${pc%%:*}" = "$id" ] || continue
          lim="$CUT"; [ "$pc" = "$id" ] || lim="${pc#*:}"
          text="$(partcell "$text" "$lim") [...] (the rest: \`{{KIT}}/doctrine/NEXT.md\`, row $id)"
        done
        printf -- '- **%s** - %s\n' "$label" "$(kitpaths "$text")"
      done
    done
    echo
  fi

  if [ "${PHASES[$s]}" != "-" ]; then
    echo "## Gate (\`{{KIT}}/AGENTS.md\` section 3: all of it, measured)"
    echo
    for p in ${PHASES[$s]}; do printf -- '- **Phase %s, %s** - %s\n' "$p" "${PNAME[$p]}" "$(kitpaths "${PGATE[$p]}")"; done
    echo
  fi

  for kind in entry when; do   # a list with no item is left out, heading and all
    n=0
    while IFS='|' read -r r k path note; do
      [ "$(trim "$r")" = "$s" ] && [ "$(trim "$k")" = "$kind" ] || continue
      path="$(trim "$path")"; note="$(trim "$note")"; n=$((n + 1))
      if [ "$n" = 1 ]; then
        if [ "$kind" = entry ]; then printf '## Read on entry\n\n'; else printf '## Read when\n\n'; fi
      fi
      if [ "$kind" = entry ]; then
        [ "$note" = "-" ] && note="${WHERE[$path]:-}"
        if [ -n "$note" ]; then printf -- '- `{{KIT}}/%s` - %s\n' "$path" "$note"; else printf -- '- `{{KIT}}/%s`\n' "$path"; fi
      else
        printf -- '- %s: `{{KIT}}/%s`\n' "$note" "$path"
      fi
    done <<< "$READS"
    [ "$n" = 0 ] || echo
  done

  echo "## Done when"
  echo
  if [ "$s" = hook-gauntlet ]; then
    echo 'The row you took is closed and its flags are updated from outputs you read. Run `{{KIT}}/scripts/next.sh <STATE.md>` (default `.gauntlet/STATE.md`, then `./STATE.md`) and load the skill its row names:'
    echo
    echo "| NEXT.md row | skill |"
    echo "|---|---|"
    for n in "${NAMES[@]}"; do
      r="$(rowlist "$n")"; [ -n "$r" ] || r="none: next.sh refused, or the machine or the kit is not yet trusted"
      printf '| %s | `%s` |\n' "$r" "$n"
    done
  elif [ "${OWNS[$s]}" = "-" ]; then
    echo 'Run `{{KIT}}/scripts/next.sh <STATE.md>` and load the skill its row names (the table is in `hook-gauntlet`).'
  else
    echo 'The row is closed and its flags updated from outputs you read. Run `{{KIT}}/scripts/next.sh <STATE.md>` and load the skill its row names (the table is in `hook-gauntlet`).'
  fi
}

